CREATE TABLE IF NOT EXISTS students (
 id BIGSERIAL PRIMARY KEY, cnie VARCHAR(255) NOT NULL UNIQUE,
 first_name VARCHAR(255) NOT NULL, last_name VARCHAR(255) NOT NULL, email VARCHAR(255) NOT NULL UNIQUE
);
ALTER TABLE students ALTER COLUMN first_name SET NOT NULL;
ALTER TABLE students ALTER COLUMN last_name SET NOT NULL;
CREATE TABLE user_accounts (
 id BIGSERIAL PRIMARY KEY, username VARCHAR(255) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(255) NOT NULL CHECK (role IN ('ADMIN','STUDENT')),
 student_id BIGINT UNIQUE REFERENCES students(id) ON DELETE CASCADE,
 CHECK ((role = 'ADMIN' AND student_id IS NULL) OR (role = 'STUDENT' AND student_id IS NOT NULL))
);
